// Builds the text of the plugin's NOTICE file (third-party notices) from
// pubspec.yaml and android/build.gradle. Used by tool/generate_notice.dart,
// which writes NOTICE, and by test/notice_test.dart, which fails while NOTICE
// is out of date.
//
// A dependency that this file does not describe fails both, so a new
// dependency cannot ship until someone checks its license and adds it here.

import 'dart:io';

const String _rule =
    '===============================================================================';

class NoticeException implements Exception {
  NoticeException(this.message);
  final String message;
  @override
  String toString() => 'NOTICE: $message';
}

/// Native dependencies that the NOTICE knows how to describe, by Gradle group.
const Map<String, String> _knownAndroidGroups = <String, String>{
  'com.github.Cynopta': 'Cynopta Android SDK',
  'com.cynopta': 'Cynopta Android SDK',
};

String buildNotice(String root) {
  final String pubspec = File('$root/pubspec.yaml').readAsStringSync();
  final String name = _match(pubspec, r'^name:\s*(\S+)', 'name in pubspec.yaml');
  final String version =
      _match(pubspec, r'^version:\s*(\S+)', 'version in pubspec.yaml');

  final Map<String, String> dartDeps = _dartDependencies(pubspec);
  final List<String> unknownDart = dartDeps.entries
      .where((MapEntry<String, String> e) => e.value != 'sdk:flutter')
      .map((MapEntry<String, String> e) => e.key)
      .toList();
  if (unknownDart.isNotEmpty) {
    throw NoticeException(
        'Dart dependencies not described in tool/notice.dart: ${unknownDart.join(', ')}. '
        'Check their licenses and add them.');
  }

  final List<String> platforms = _platforms(pubspec);
  final List<String> unsupported =
      platforms.where((String p) => p != 'android').toList();
  if (unsupported.isNotEmpty) {
    throw NoticeException(
        'platforms not described in tool/notice.dart: ${unsupported.join(', ')}. '
        "Add that platform's native SDK to the NOTICE.");
  }

  final List<List<String>> androidDeps = <List<String>>[];
  if (platforms.contains('android')) {
    final String gradle = File('$root/android/build.gradle').readAsStringSync();
    final RegExp dep = RegExp(
        r'''^\s*(?:api|implementation|runtimeOnly)\s*\(?\s*["']([^"':]+):([^"':]+):([^"']+)["']''',
        multiLine: true);
    for (final RegExpMatch m in dep.allMatches(gradle)) {
      final String group = m.group(1)!;
      if (!_knownAndroidGroups.containsKey(group)) {
        throw NoticeException(
            'Android dependency not described in tool/notice.dart: '
            '$group:${m.group(2)}:${m.group(3)}. Check its license and add it.');
      }
      androidDeps.add(<String>[group, m.group(2)!, m.group(3)!]);
    }
  }

  final StringBuffer out = StringBuffer()
    ..writeln('Cynopta Flutter plugin ($name)')
    ..writeln('Third-party notices')
    ..writeln()
    ..writeln('Copyright (c) Cynopta, Inc. All rights reserved.')
    ..writeln()
    ..writeln('This file applies to $name, version $version. The plugin supports')
    ..writeln('${platforms.map(_platformName).join(' and ')}.')
    ..writeln()
    ..writeln("The plugin's own code is Cynopta's. The native Cynopta SDK that the plugin")
    ..writeln('adds to your app is licensed, not sold, under the Cynopta SDK License')
    ..writeln('Agreement: https://www.cynopta.com/sdk-license.html')
    ..writeln()
    ..writeln('The plugin contains no third-party code. It depends on the components')
    ..writeln('listed below, which your build adds to your app.')
    ..writeln()
    ..writeln('Questions: legal@cynopta.com')
    ..writeln()
    ..writeln('This file is generated by tool/generate_notice.dart from pubspec.yaml and')
    ..writeln('android/build.gradle. flutter test fails while it is out of date.')
    ..writeln()
    ..writeln()
    ..writeln(_rule)
    ..writeln('1. Native SDKs')
    ..writeln(_rule)
    ..writeln();
  int n = 0;
  for (final List<String> d in androidDeps) {
    n++;
    out
      ..writeln('1.$n ${_knownAndroidGroups[d[0]]}')
      ..writeln('    Component:  ${d[0]}:${d[1]} ${d[2]}')
      ..writeln('    Platform:   Android')
      ..writeln("    Notices:    the SDK's own NOTICE file, at the root of its AAR, lists the")
      ..writeln('                third-party components it depends on and their licenses.')
      ..writeln();
  }
  out
    ..writeln()
    ..writeln(_rule)
    ..writeln('2. Flutter SDK')
    ..writeln(_rule)
    ..writeln()
    ..writeln('2.1 Flutter')
    ..writeln('    Component:  flutter, from your Flutter installation')
    ..writeln('    Source:     https://github.com/flutter/flutter')
    ..writeln('    License:    BSD 3-Clause License')
    ..writeln('                https://github.com/flutter/flutter/blob/master/LICENSE')
    ..writeln('    Note:       Your Flutter installation provides it under its own license.')
    ..writeln('                The plugin does not include a copy.');
  return out.toString();
}

String _platformName(String p) =>
    const <String, String>{'android': 'Android', 'ios': 'iOS'}[p] ?? p;

String _match(String text, String pattern, String what) {
  final RegExpMatch? m = RegExp(pattern, multiLine: true).firstMatch(text);
  if (m == null) {
    throw NoticeException('could not find the $what');
  }
  return m.group(1)!;
}

/// Top-level `dependencies:` of pubspec.yaml: name -> "sdk:<sdk>" or "other".
Map<String, String> _dartDependencies(String pubspec) {
  final Map<String, String> deps = <String, String>{};
  final List<String> lines = pubspec.split('\n');
  final int start = lines.indexWhere((String l) => l.trimRight() == 'dependencies:');
  if (start < 0) {
    return deps;
  }
  String? current;
  for (final String line in lines.skip(start + 1)) {
    if (line.trim().isEmpty || line.trimLeft().startsWith('#')) {
      continue;
    }
    if (!line.startsWith(' ')) {
      break;
    }
    final RegExpMatch? entry = RegExp(r'^  ([A-Za-z0-9_]+):').firstMatch(line);
    if (entry != null) {
      current = entry.group(1);
      deps[current!] = 'other';
      continue;
    }
    final RegExpMatch? sdk = RegExp(r'^\s+sdk:\s*(\S+)').firstMatch(line);
    if (current != null && sdk != null) {
      deps[current] = 'sdk:${sdk.group(1)}';
    }
  }
  return deps;
}

/// Platforms under flutter: plugin: platforms: in pubspec.yaml.
List<String> _platforms(String pubspec) {
  final List<String> lines = pubspec.split('\n');
  final int start = lines.indexWhere((String l) => l.trim() == 'platforms:');
  if (start < 0) {
    return <String>[];
  }
  final int indent = lines[start].indexOf('platforms:') + 2;
  final List<String> result = <String>[];
  for (final String line in lines.skip(start + 1)) {
    if (line.trim().isEmpty) {
      continue;
    }
    final int lead = line.length - line.trimLeft().length;
    if (lead < indent) {
      break;
    }
    final RegExpMatch? key = RegExp(r'^\s+([a-z]+):\s*$').firstMatch(line);
    if (lead == indent && key != null) {
      result.add(key.group(1)!);
    }
  }
  return result;
}
